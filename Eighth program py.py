class Account:
    def __init__(self,balance,account_no):
        self.balance=balance
        self.account_no=account_no
    def debit(self,amount):
        self.balance-=amount
        print("debit",amount,"in your account")
    def credit(self,amount):
        self.balance+=amount
        print("credit",amount,"in your account")
    def remain_balance(self):
        return self.balance

bank=Account(50000,292238505)
print(bank.balance,bank.account_no)
bank.debit(5000)
bank.credit(2000)
print(bank.account_no,bank.remain_balance())
